#!/usr/bin/env python3
"""Build the short instrument tunes in sounds.js from tonejs-instruments samples.

Usage: python3 tools/make_sounds.py <dir with unpacked tonejs-instrument-*-mp3 packages>
Each package is expected at <dir>/<instrument>/package/<Note>.mp3 (npm pack + tar xzf).
Requires ffmpeg. Writes sounds.js next to index.html.
"""
import base64, json, os, subprocess, sys, tempfile

# quiz id -> (sample package, [(note, start_s, length_s), ...])
TUNES = {
    "piano":     ("piano",           [("C4", 0, .5), ("E4", .4, .5), ("G4", .8, .5), ("C5", 1.2, 1.6)]),
    "violin":    ("violin",          [("G4", 0, .6), ("C5", .55, .6), ("E5", 1.1, .6), ("G5", 1.65, 1.4)]),
    "guitar":    ("guitar-acoustic", [(n, i * .06, 1.4) for i, n in enumerate(["C3", "E3", "G3", "C4", "E4"])]
                                   + [(n, 1.3 + i * .06, 1.8) for i, n in enumerate(["C3", "E3", "G3", "C4", "E4"])]),
    "trumpet":   ("trumpet",         [("G4", 0, .22), ("G4", .25, .22), ("G4", .5, .22), ("D5", .8, 1.6)]),
    "saxophone": ("saxophone",       [("C4", 0, .3), ("Ds4", .3, .3), ("F4", .6, .3), ("Fs4", .9, .3), ("G4", 1.2, 1.4)]),
    "flute":     ("flute",           [("A5", 0, .3), ("C6", .3, .3), ("A5", .6, .3), ("C6", .9, .3), ("E5", 1.2, 1.4)]),
    "accordion": ("harmonium",       [(n, 0, .7) for n in ["C4", "E4", "G4"]]
                                   + [(n, .8, .7) for n in ["F4", "A4", "C5"]]
                                   + [(n, 1.6, 1.2) for n in ["C4", "E4", "G4"]]),
}

def build(src_dir, notes, out):
    inputs, filters = [], []
    for k, (note, start, length) in enumerate(notes):
        inputs += ["-i", os.path.join(src_dir, "package", note + ".mp3")]
        fade = min(.25, length / 2)
        filters.append(f"[{k}:a]atrim=0:{length},asetpts=PTS-STARTPTS,"
                       f"afade=t=out:st={length - fade}:d={fade},adelay={int(start * 1000)}:all=1[n{k}]")
    mix = "".join(f"[n{k}]" for k in range(len(notes)))
    filters.append(f"{mix}amix=inputs={len(notes)}:normalize=0,loudnorm=I=-16:TP=-1.5,aresample=44100[out]")
    subprocess.run(["ffmpeg", "-v", "error", "-y", *inputs, "-filter_complex", ";".join(filters),
                    "-map", "[out]", "-ac", "1", "-b:a", "64k", out], check=True)

def main(samples):
    data = {}
    with tempfile.TemporaryDirectory() as tmp:
        for quiz_id, (pkg, notes) in TUNES.items():
            out = os.path.join(tmp, quiz_id + ".mp3")
            build(os.path.join(samples, pkg), notes, out)
            data[quiz_id] = "data:audio/mpeg;base64," + base64.b64encode(open(out, "rb").read()).decode()
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    with open(os.path.join(root, "sounds.js"), "w") as f:
        f.write("// Generated by tools/make_sounds.py — real instrument recordings, see README for credits.\n")
        f.write("window.INSTRUMENT_SOUNDS = " + json.dumps(data, indent=1) + ";\n")

if __name__ == "__main__":
    main(sys.argv[1])
