#!/usr/bin/env python3
"""Build pictures.js: instrument pictures as SVG data URIs.

Usage: python3 tools/make_pictures.py <@iconify-json/noto icons.json>
Most pictures are Noto Emoji (Apache-2.0); xylophone, triangle and tambourine are drawn
by hand in pictures/. Get icons.json with: npm pack @iconify-json/noto && tar xzf iconify-json-noto-*.tgz
"""
import json, os, sys, urllib.parse

NOTO = {
    "guitar": "guitar", "piano": "musical-keyboard", "trumpet": "trumpet", "violin": "violin",
    "drum": "drum", "saxophone": "saxophone", "accordion": "accordion", "banjo": "banjo",
    "flute": "flute", "maracas": "maracas", "bell": "bell", "harp": "harp",
    "trombone": "trombone", "horn": "postal-horn",
}
OWN = ["xylophone", "triangle", "tambourine"]

def data_uri(svg):
    return "data:image/svg+xml," + urllib.parse.quote(" ".join(svg.split()), safe=" =:/;,'()<>.-")

def main(icons_json):
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    d = json.load(open(icons_json))
    pics = {}
    for quiz_id, name in NOTO.items():
        icon = d["icons"][name]
        w, h = icon.get("width", d.get("width", 16)), icon.get("height", d.get("height", 16))
        pics[quiz_id] = data_uri(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}">{icon["body"]}</svg>')
    for quiz_id in OWN:
        pics[quiz_id] = data_uri(open(os.path.join(root, "pictures", quiz_id + ".svg")).read())
    with open(os.path.join(root, "pictures.js"), "w") as f:
        f.write("// Generated by tools/make_pictures.py — Noto Emoji (Apache-2.0) + pictures/*.svg\n")
        f.write("window.INSTRUMENT_PICTURES = " + json.dumps(dict(sorted(pics.items())), indent=1) + ";\n")

if __name__ == "__main__":
    main(sys.argv[1])
