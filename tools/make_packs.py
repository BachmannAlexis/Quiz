#!/usr/bin/env python3
"""Write app/packs.js: the version (a short hash of the content) and size of every pack the app loads on demand:
app/pictures/*.js, app/sounds/*.js, app/voice/<lang>/*.json and app/photos/*.json.

The app adds the version to each pack's URL, so the service worker can keep a pack on the phone until it changes,
and the offline download knows what to fetch and how big it is. The tools that write packs run this at the end.

Usage: python3 tools/make_packs.py
"""
import hashlib, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def main():
    packs = {}
    for folder in ("pictures", "sounds", "voice", "photos"):
        base = os.path.join(ROOT, "app", folder)
        for dirpath, _, files in os.walk(base):
            for f in sorted(files):
                if not f.endswith((".js", ".json")): continue
                path = os.path.join(dirpath, f)
                data = open(path, "rb").read()
                packs[os.path.relpath(path, os.path.join(ROOT, "app"))] = [hashlib.sha1(data).hexdigest()[:10], len(data)]
    with open(os.path.join(ROOT, "app", "packs.js"), "w") as f:
        f.write("// Generated by tools/make_packs.py: path -> [version, bytes] of every pack loaded on demand.\n")
        f.write("const PACKS = {\n" + ",\n".join(f"  {json.dumps(k)}: {json.dumps(v)}" for k, v in sorted(packs.items())) + "\n};\n")
    print(len(packs), "packs in app/packs.js")

if __name__ == "__main__":
    main()
